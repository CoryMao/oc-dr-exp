#!/usr/bin/env python3
"""Run DeepSeek judge batches and collect JSONL judgments.

The script reads prompts generated by build_judge_inputs.py and writes:
  - raw_responses/batch_XXX.json
  - judgments.jsonl

API key is read only from DEEPSEEK_API_KEY. Do not hard-code keys.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import ssl
import socket
import time
import urllib.error
import urllib.request
from urllib.parse import urlparse
from pathlib import Path


ITEM_RE = re.compile(r'^\{"citation": .*"item_id": "([^"]+)".*\}$')


def extract_expected_item_ids(prompt_text: str) -> list[str]:
    ids = []
    for line in prompt_text.splitlines():
        line = line.strip()
        if not line.startswith('{"citation": '):
            continue
        try:
            ids.append(json.loads(line)["item_id"])
        except Exception:
            match = ITEM_RE.match(line)
            if match:
                ids.append(match.group(1))
    return ids


def parse_jsonl_from_text(text: str) -> list[dict]:
    rows = []
    in_fence = False
    for raw in text.splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("```"):
            in_fence = not in_fence
            continue
        if not line.startswith("{"):
            continue
        try:
            obj = json.loads(line)
        except json.JSONDecodeError:
            continue
        if isinstance(obj, dict) and "item_id" in obj:
            rows.append(obj)
    return rows


def request_deepseek(
    *,
    api_key: str,
    prompt_text: str,
    model: str,
    base_url: str,
    timeout: int,
    max_tokens: int,
    thinking: str,
    reasoning_effort: str,
    no_proxy: bool,
    ca_file: str,
    insecure_skip_verify: bool,
) -> dict:
    payload = {
        "model": model,
        "messages": [
            {
                "role": "system",
                "content": "你是学术引用忠实度核验员。严格按用户给定格式输出，不要添加无关文字。",
            },
            {"role": "user", "content": prompt_text},
        ],
        "thinking": {"type": thinking},
        "reasoning_effort": reasoning_effort,
        "max_tokens": max_tokens,
        "stream": False,
    }
    data = json.dumps(payload, ensure_ascii=False).encode("utf-8")
    req = urllib.request.Request(
        base_url.rstrip("/") + "/chat/completions",
        data=data,
        method="POST",
        headers={
            "Content-Type": "application/json",
            "Authorization": f"Bearer {api_key}",
        },
    )
    ssl_context = None
    if insecure_skip_verify:
        ssl_context = ssl._create_unverified_context()  # noqa: SLF001
    elif ca_file:
        ssl_context = ssl.create_default_context(cafile=ca_file)

    handlers = []
    if no_proxy:
        handlers.append(urllib.request.ProxyHandler({}))
    if ssl_context is not None:
        handlers.append(urllib.request.HTTPSHandler(context=ssl_context))
    opener = urllib.request.build_opener(*handlers) if handlers else urllib.request.build_opener()

    with opener.open(req, timeout=timeout) as resp:
        return json.loads(resp.read().decode("utf-8"))


def response_content(response: dict) -> str:
    try:
        return response["choices"][0]["message"]["content"] or ""
    except Exception:
        return ""


def sanitized_proxy_env() -> dict[str, str]:
    keys = ["HTTPS_PROXY", "HTTP_PROXY", "ALL_PROXY", "NO_PROXY", "https_proxy", "http_proxy", "all_proxy", "no_proxy"]
    values = {}
    for key in keys:
        value = os.environ.get(key)
        if value:
            values[key] = re.sub(r"//[^/@]+@", "//<redacted>@", value)
    return values


def tls_connect_test(base_url: str, timeout: int, no_proxy: bool, ca_file: str, insecure_skip_verify: bool) -> None:
    parsed = urlparse(base_url)
    host = parsed.hostname or base_url.replace("https://", "").split("/", 1)[0]
    port = parsed.port or 443
    print(json.dumps({"event": "connect_test_start", "host": host, "port": port, "no_proxy": no_proxy}, ensure_ascii=False), flush=True)
    started = time.time()
    if no_proxy:
        context = ssl._create_unverified_context() if insecure_skip_verify else ssl.create_default_context(cafile=ca_file or None)  # noqa: SLF001
        with socket.create_connection((host, port), timeout=timeout) as sock:
            with context.wrap_socket(sock, server_hostname=host) as tls:
                cert = tls.getpeercert()
                print(
                    json.dumps(
                        {
                            "event": "connect_test_ok",
                            "tls_version": tls.version(),
                            "subject": cert.get("subject", [])[:1],
                            "elapsed_sec": round(time.time() - started, 3),
                        },
                        ensure_ascii=False,
                    ),
                    flush=True,
                )
        return

    req = urllib.request.Request(base_url.rstrip("/") + "/", method="HEAD")
    ssl_context = None
    if insecure_skip_verify:
        ssl_context = ssl._create_unverified_context()  # noqa: SLF001
    elif ca_file:
        ssl_context = ssl.create_default_context(cafile=ca_file)
    handlers = [urllib.request.HTTPSHandler(context=ssl_context)] if ssl_context is not None else []
    opener = urllib.request.build_opener(*handlers)
    try:
        with opener.open(req, timeout=timeout) as resp:
            status = resp.status
    except urllib.error.HTTPError as exc:
        status = exc.code
    print(
        json.dumps(
            {"event": "connect_test_ok", "http_status": status, "elapsed_sec": round(time.time() - started, 3)},
            ensure_ascii=False,
        ),
        flush=True,
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--batch-dir", required=True)
    parser.add_argument("--out-dir", required=True)
    parser.add_argument("--model", default="deepseek-v4-pro")
    parser.add_argument("--base-url", default="https://api.deepseek.com")
    parser.add_argument("--thinking", choices=["enabled", "disabled"], default="enabled")
    parser.add_argument("--reasoning-effort", choices=["high", "max"], default="high")
    parser.add_argument("--max-tokens", type=int, default=4096)
    parser.add_argument("--timeout", type=int, default=600)
    parser.add_argument("--retries", type=int, default=2)
    parser.add_argument("--sleep-seconds", type=float, default=2.0)
    parser.add_argument("--limit", type=int, default=0)
    parser.add_argument("--resume", action="store_true")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--no-proxy", action="store_true", help="Ignore HTTPS_PROXY/HTTP_PROXY env vars for DeepSeek requests.")
    parser.add_argument("--ca-file", default="", help="Custom CA bundle path for HTTPS verification.")
    parser.add_argument(
        "--insecure-skip-verify",
        action="store_true",
        help="Disable TLS certificate verification. Use only as a temporary workaround for local proxy MITM cert issues.",
    )
    parser.add_argument("--connect-test", action="store_true", help="Only test HTTPS connectivity to the DeepSeek API endpoint.")
    parser.add_argument("--verbose", action="store_true")
    args = parser.parse_args()

    api_key = os.environ.get("DEEPSEEK_API_KEY", "")
    if args.verbose:
        print(
            json.dumps(
                {
                    "event": "config",
                    "base_url": args.base_url,
                    "model": args.model,
                    "reasoning_effort": args.reasoning_effort,
                    "thinking": args.thinking,
                    "no_proxy": args.no_proxy,
                    "insecure_skip_verify": args.insecure_skip_verify,
                    "proxy_env": sanitized_proxy_env(),
                    "api_key_set": bool(api_key),
                },
                ensure_ascii=False,
                sort_keys=True,
            ),
            flush=True,
        )
    if args.connect_test:
        tls_connect_test(args.base_url, min(args.timeout, 30), args.no_proxy, args.ca_file, args.insecure_skip_verify)
        return 0
    if not api_key and not args.dry_run:
        raise SystemExit("DEEPSEEK_API_KEY is not set. Export it in your shell before running.")

    batch_dir = Path(args.batch_dir)
    out_dir = Path(args.out_dir)
    raw_dir = out_dir / "raw_responses"
    raw_dir.mkdir(parents=True, exist_ok=True)
    judgments_path = out_dir / "judgments.jsonl"

    batch_files = sorted(batch_dir.glob("batch_*.txt"))
    if args.limit:
        batch_files = batch_files[: args.limit]
    if not batch_files:
        raise SystemExit(f"No batch_*.txt files found under {batch_dir}")

    existing_ids: set[str] = set()
    if args.resume and judgments_path.exists():
        for line in judgments_path.read_text(encoding="utf-8").splitlines():
            if line.strip():
                try:
                    existing_ids.add(json.loads(line)["item_id"])
                except Exception:
                    pass

    if args.dry_run:
        for batch_file in batch_files:
            ids = extract_expected_item_ids(batch_file.read_text(encoding="utf-8"))
            print(f"{batch_file.name}: {len(ids)} items")
        return 0

    with judgments_path.open("a" if args.resume else "w", encoding="utf-8") as out:
        for batch_file in batch_files:
            prompt_text = batch_file.read_text(encoding="utf-8")
            expected_ids = extract_expected_item_ids(prompt_text)
            if args.resume and expected_ids and all(item_id in existing_ids for item_id in expected_ids):
                print(f"skip {batch_file.name}: already judged")
                continue

            raw_path = raw_dir / f"{batch_file.stem}.json"
            last_error = None
            response = None
            for attempt in range(args.retries + 1):
                try:
                    if args.verbose:
                        print(
                            json.dumps(
                                {
                                    "event": "request_start",
                                    "batch": batch_file.name,
                                    "attempt": attempt + 1,
                                    "expected_items": len(expected_ids),
                                    "prompt_bytes": len(prompt_text.encode("utf-8")),
                                },
                                ensure_ascii=False,
                                sort_keys=True,
                            ),
                            flush=True,
                        )
                    started = time.time()
                    response = request_deepseek(
                        api_key=api_key,
                        prompt_text=prompt_text,
                        model=args.model,
                        base_url=args.base_url,
                        timeout=args.timeout,
                        max_tokens=args.max_tokens,
                        thinking=args.thinking,
                        reasoning_effort=args.reasoning_effort,
                        no_proxy=args.no_proxy,
                        ca_file=args.ca_file,
                        insecure_skip_verify=args.insecure_skip_verify,
                    )
                    if args.verbose:
                        print(
                            json.dumps(
                                {
                                    "event": "request_done",
                                    "batch": batch_file.name,
                                    "elapsed_sec": round(time.time() - started, 3),
                                },
                                ensure_ascii=False,
                                sort_keys=True,
                            ),
                            flush=True,
                        )
                    break
                except urllib.error.HTTPError as exc:
                    body = exc.read().decode("utf-8", errors="replace")
                    last_error = f"HTTP {exc.code}: {body[:500]}"
                except Exception as exc:  # noqa: BLE001
                    last_error = repr(exc)
                if args.verbose:
                    print(
                        json.dumps(
                            {"event": "request_error", "batch": batch_file.name, "attempt": attempt + 1, "error": last_error},
                            ensure_ascii=False,
                            sort_keys=True,
                        ),
                        flush=True,
                    )
                if attempt < args.retries:
                    time.sleep(args.sleep_seconds * (attempt + 1))
            if response is None:
                raise SystemExit(f"{batch_file.name} failed after retries: {last_error}")

            raw_path.write_text(json.dumps(response, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
            content = response_content(response)
            rows = parse_jsonl_from_text(content)
            found_ids = {row.get("item_id") for row in rows}
            missing = [item_id for item_id in expected_ids if item_id not in found_ids]
            for row in rows:
                out.write(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n")
            out.flush()
            usage = response.get("usage", {})
            print(
                json.dumps(
                    {
                        "batch": batch_file.name,
                        "expected": len(expected_ids),
                        "parsed": len(rows),
                        "missing": missing,
                        "usage": usage,
                    },
                    ensure_ascii=False,
                    sort_keys=True,
                )
            )
            time.sleep(args.sleep_seconds)

    print(f"wrote judgments to {judgments_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
